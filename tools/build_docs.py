#!/usr/bin/env python3
"""Builds the docs guide data from content/docs/*.md.

Each guide is a Markdown file with a small front matter block:

    ---
    title: Quickstart
    group: Get started
    order: 2
    description: One sentence for search results and llms.txt.
    ---

Writes app/js/lib/docs.js (used by the docs site) and an identical copy at
supabase/functions/delivrie/docs.js (used by "Ask Delivrie" and GET /api/docs).
Run by tools/build_seo.py, or on its own: python3 tools/build_docs.py
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "content", "docs")
GROUP_ORDER = ["Get started", "SDKs and frameworks", "Integrations", "Sending", "Receiving", "Platform", "Help"]

SEARCH = r'''
export function searchDocs(q, n = 3) {
  const words = String(q || "").toLowerCase().match(/[a-z0-9_]+/g) || [];
  const stop = new Set(["the", "a", "an", "is", "my", "i", "how", "do", "to", "of", "and", "or", "what", "why", "can", "in", "for", "on", "with", "it", "does", "are"]);
  const terms = words.filter((w) => !stop.has(w) && w.length > 1);
  return DOCS.map((d) => {
    const t = d.title.toLowerCase(), b = d.body.toLowerCase();
    let score = 0;
    for (const w of terms) {
      if (t.includes(w)) score += 4;
      const hits = b.split(w).length - 1;
      score += Math.min(hits, 5);
      if (w.endsWith("s") && b.includes(w.slice(0, -1))) score += 1;
    }
    return { doc: d, score };
  }).filter((x) => x.score > 0).sort((a, b) => b.score - a.score).slice(0, n).map((x) => x.doc);
}
'''


def parse(path):
    raw = open(path, encoding="utf-8").read()
    m = re.match(r"^---\n(.*?)\n---\n", raw, re.S)
    if not m:
        sys.exit(f"{path}: missing front matter")
    meta = {}
    for line in m.group(1).splitlines():
        k, _, v = line.partition(":")
        meta[k.strip()] = v.strip()
    for k in ("title", "group", "order", "description"):
        if not meta.get(k):
            sys.exit(f"{path}: front matter needs {k}")
    if meta["group"] not in GROUP_ORDER:
        sys.exit(f"{path}: unknown group {meta['group']!r}")
    return {
        "id": os.path.splitext(os.path.basename(path))[0],
        "title": meta["title"],
        "group": meta["group"],
        "order": float(meta["order"]),
        "description": meta["description"],
        "body": raw[m.end():].strip() + "\n",
    }


def load():
    docs = [parse(os.path.join(SRC, f)) for f in sorted(os.listdir(SRC)) if f.endswith(".md")]
    docs.sort(key=lambda d: (GROUP_ORDER.index(d["group"]), d["order"], d["title"]))
    ids = [d["id"] for d in docs]
    if len(ids) != len(set(ids)):
        sys.exit("duplicate guide ids")
    # Every internal /docs/<id> link must point at a guide, the API reference, the MCP page or the changelog.
    known = set(ids) | {"api", "mcp", "changelog"}
    for d in docs:
        for target in re.findall(r"\]\(/docs/([a-z0-9-]+)", d["body"]):
            if target not in known:
                sys.exit(f"{d['id']}.md links to /docs/{target}, which doesn't exist")
    return docs


def build():
    docs = load()
    groups = []
    for g in GROUP_ORDER:
        items = [[d["id"], d["title"]] for d in docs if d["group"] == g]
        if items:
            groups.append([g, items])
    out = [d.copy() for d in docs]
    for d in out:
        d.pop("order")
    js = ("// Generated by tools/build_docs.py from content/docs/*.md. Edit the Markdown, not this file.\n"
          "// Used by the docs site, and by \"Ask Delivrie\" and GET /api/docs on the server.\n"
          f"export const GROUPS = {json.dumps(groups, ensure_ascii=False)};\n"
          f"export const DOCS = {json.dumps(out, ensure_ascii=False, indent=1)};\n" + SEARCH)
    for rel in ("app/js/lib/docs.js", "supabase/functions/delivrie/docs.js"):
        with open(os.path.join(ROOT, rel), "w", encoding="utf-8") as f:
            f.write(js)
    # The email renderer is shared by the dashboard and the server: keep the server copy in step.
    with open(os.path.join(ROOT, "app/js/lib/blocks.js"), encoding="utf-8") as f:
        blocks = f.read()
    with open(os.path.join(ROOT, "supabase/functions/delivrie/blocks.js"), "w", encoding="utf-8") as f:
        f.write(blocks)
    return docs


if __name__ == "__main__":
    print(f"built {len(build())} guides")
