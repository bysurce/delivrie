def camel(s): p = s.split("_"); return p[0] + "".join(x.title() for x in p[1:])
def pascal(s): return "".join(x.title() for x in s.split("_"))

def path_parts(path):
    """'/emails/{id}/cancel' -> ('/emails/', '/cancel') or (path, None) when there's no id."""
    if "{id}" not in path: return path, None
    a, b = path.split("{id}")
    return a, b

